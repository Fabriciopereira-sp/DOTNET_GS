-- Voz & Via - tabelas da API .NET (zeladoria) no Oracle
-- Para o colega de Banco incluir no scripts/script-bd.sql do grupo.
-- Nomes de tabelas e colunas iguais aos usados pela API (EF Core, sem migrations).
--
-- Ordem: VV_ORGAO precisa existir antes de VV_USUARIO (tabela do Java), porque
-- VV_USUARIO.ORGAO_ID referencia VV_ORGAO. As demais dependem de VV_USUARIO.

CREATE TABLE VV_ORGAO (
    ID      NUMBER(19)      GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOME    NVARCHAR2(120)  NOT NULL,
    AREA    NVARCHAR2(20)   NOT NULL,
    CONSTRAINT CK_VV_ORGAO_AREA CHECK (AREA IN ('OBRAS', 'ILUMINACAO', 'MOBILIDADE', 'LIMPEZA'))
);

CREATE TABLE VV_CATEGORIA (
    ID        NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CODIGO    NVARCHAR2(30)  NOT NULL,
    NOME      NVARCHAR2(80)  NOT NULL,
    ORGAO_ID  NUMBER(19)     NOT NULL,
    CONSTRAINT UK_VV_CATEGORIA_CODIGO UNIQUE (CODIGO),
    CONSTRAINT FK_VV_CATEGORIA_ORGAO FOREIGN KEY (ORGAO_ID) REFERENCES VV_ORGAO (ID)
);

-- VV_USUARIO é criada pelo script do Java. Colunas lidas pela API .NET:
-- ID, NOME, EMAIL, ROLE, ORGAO_ID (FK para VV_ORGAO, preenchida só para GESTOR) e CRIADO_EM.

CREATE TABLE VV_REPORTE (
    ID             NUMBER(19)      GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PROTOCOLO      NVARCHAR2(20)   NOT NULL,
    USUARIO_ID     NUMBER(19)      NOT NULL,
    CATEGORIA_ID   NUMBER(19)      NOT NULL,
    ORGAO_ID       NUMBER(19)      NOT NULL,
    DESCRICAO      NVARCHAR2(500)  NOT NULL,
    LATITUDE       NUMBER(9,6)     NOT NULL,
    LONGITUDE      NUMBER(9,6)     NOT NULL,
    ENDERECO       NVARCHAR2(200),
    FOTO_URL       NVARCHAR2(500),
    URGENCIA       NVARCHAR2(10)   NOT NULL,
    STATUS         NVARCHAR2(20)   NOT NULL,
    PRIORIDADE     NUMBER(10)      NOT NULL,
    CRIADO_EM      TIMESTAMP(7)    NOT NULL,
    ATUALIZADO_EM  TIMESTAMP(7)    NOT NULL,
    CONSTRAINT UK_VV_REPORTE_PROTOCOLO UNIQUE (PROTOCOLO),
    CONSTRAINT FK_VV_REPORTE_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES VV_USUARIO (ID),
    CONSTRAINT FK_VV_REPORTE_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES VV_CATEGORIA (ID),
    CONSTRAINT FK_VV_REPORTE_ORGAO FOREIGN KEY (ORGAO_ID) REFERENCES VV_ORGAO (ID),
    CONSTRAINT CK_VV_REPORTE_URGENCIA CHECK (URGENCIA IN ('BAIXA', 'MEDIA', 'ALTA')),
    CONSTRAINT CK_VV_REPORTE_STATUS CHECK (STATUS IN ('ABERTO', 'EM_ANALISE', 'EM_EXECUCAO', 'RESOLVIDO', 'CANCELADO'))
);

CREATE TABLE VV_HISTORICO_STATUS (
    ID               NUMBER(19)      GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    REPORTE_ID       NUMBER(19)      NOT NULL,
    STATUS_ANTERIOR  NVARCHAR2(20),
    STATUS_NOVO      NVARCHAR2(20)   NOT NULL,
    OBSERVACAO       NVARCHAR2(300),
    USUARIO_ID       NUMBER(19)      NOT NULL,
    CRIADO_EM        TIMESTAMP(7)    NOT NULL,
    CONSTRAINT FK_VV_HISTORICO_REPORTE FOREIGN KEY (REPORTE_ID) REFERENCES VV_REPORTE (ID) ON DELETE CASCADE
);

CREATE TABLE VV_IDEMPOTENCIA (
    CHAVE          NVARCHAR2(100)  NOT NULL,
    USUARIO_ID     NUMBER(19)      NOT NULL,
    HASH_CORPO     NVARCHAR2(64)   NOT NULL,
    STATUS_HTTP    NUMBER(10)      NOT NULL,
    RESPOSTA_JSON  NCLOB,
    CRIADO_EM      TIMESTAMP(7)    NOT NULL,
    CONSTRAINT PK_VV_IDEMPOTENCIA PRIMARY KEY (CHAVE, USUARIO_ID)
);

CREATE INDEX IX_VV_REPORTE_USUARIO ON VV_REPORTE (USUARIO_ID);
CREATE INDEX IX_VV_REPORTE_FILA ON VV_REPORTE (ORGAO_ID, STATUS, PRIORIDADE);

